/**
 * Interpolate `{n}`, `{total}`, `{name}` style placeholders.
 */
export function formatAidCopy(template, vars = {}) {
  if (!template) return '';
  return String(template).replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] != null ? String(vars[key]) : '',
  );
}

/** Pick display label from option; prefers labelUr when lang is ur. */
export function aidOptionLabel(opt, lang = 'en') {
  if (!opt) return '';
  if (lang === 'ur' && opt.labelUr) return opt.labelUr;
  return opt.label || '';
}

/** Map option list for selects with bilingual labels. */
export function aidOptionsForLang(options, lang = 'en') {
  if (!Array.isArray(options)) return [];
  return options.map((o) => ({
    ...o,
    label: aidOptionLabel(o, lang),
  }));
}
